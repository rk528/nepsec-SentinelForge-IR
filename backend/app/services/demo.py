"""Synthetic demo workspace: seeding, scenario injection and reset.

The demo organisation is flagged ``is_demo`` and every record it contains is
synthetic. Demo users have no password and can only sign in when
DEMO_MODE=true. Reset deletes only the demo organisation.
"""

from __future__ import annotations

import random
import uuid
from collections import defaultdict
from datetime import UTC, datetime, timedelta
from typing import Any

from fastapi import HTTPException
from sqlalchemy import delete, select, text
from sqlalchemy.orm import Session

from app import audit
from app.audit import RequestContext
from app.detection.engine import run_detection, sync_rule_metadata
from app.models import Alert, DataSource, Incident, IncidentNote, Indicator, Organization, User
from app.playbooks.registry import sync_playbooks
from app.services import incidents as inc_svc
from app.services.ingest import ingest_events
from app.services.scenarios import SCENARIOS, SYNTHETIC_SOURCES, background_noise

DEMO_SLUG = "demo"
DEMO_ORG_NAME = "Northwind Demo SOC (synthetic)"
DEMO_USERS = [
    ("analyst@demo.sentinelforge.invalid", "Demo Analyst", "analyst"),
    ("analyst2@demo.sentinelforge.invalid", "Demo Analyst Two", "analyst"),
    ("lead@demo.sentinelforge.invalid", "Demo Lead", "lead"),
    ("viewer@demo.sentinelforge.invalid", "Demo Viewer", "viewer"),
]
RESET_CONFIRMATION = "RESET DEMO DATA"


def demo_org(db: Session) -> Organization | None:
    return db.execute(select(Organization).where(Organization.slug == DEMO_SLUG)).scalar_one_or_none()


def ensure_synthetic_sources(db: Session, org_id: uuid.UUID) -> dict[str, DataSource]:
    existing = {s.name: s for s in db.execute(select(DataSource).where(DataSource.org_id == org_id)).scalars()}
    out: dict[str, DataSource] = {}
    for key, (name, stype) in SYNTHETIC_SOURCES.items():
        src = existing.get(name)
        if src is None:
            src = DataSource(org_id=org_id, name=name, source_type=stype, is_synthetic=True, description="Synthetic telemetry generated by SentinelForge scenarios.")
            db.add(src)
            db.flush()
        out[key] = src
    return out


def run_scenario(db: Session, ctx: RequestContext, org_id: uuid.UUID, scenario_id: str, at: datetime, *, variant: str = "") -> dict[str, Any]:
    scenario = SCENARIOS.get(scenario_id)
    if scenario is None and scenario_id != "background":
        raise HTTPException(status_code=404, detail="Scenario not found")
    builder = scenario.build if scenario else background_noise
    sources = ensure_synthetic_sources(db, org_id)
    grouped: dict[str, list] = defaultdict(list)
    for key, ev in builder(at, variant):
        grouped[key].append(ev)
    inserted = 0
    earliest = at
    for key, events in grouped.items():
        res = ingest_events(db, org_id, sources[key], events, synthetic=True, scenario_id=scenario_id)
        inserted += res.inserted
        if res.earliest and res.earliest < earliest:
            earliest = res.earliest
    db.flush()
    summary = run_detection(db, org_id, since=earliest, until=datetime.now(UTC), ctx=ctx)
    audit.record(db, ctx, "scenario.run", target_type="scenario", target_id=scenario_id, details={"inserted": inserted, "alerts_created": summary.alerts_created})
    return {
        "scenario_id": scenario_id,
        "events_inserted": inserted,
        "alerts_created": summary.alerts_created,
        "alerts_updated": summary.alerts_updated,
        "expected_rules": scenario.expected_rules if scenario else [],
    }


def _note(db: Session, incident: Incident, author: User, body: str, at: datetime, note_type: str = "analyst") -> None:
    db.add(IncidentNote(org_id=incident.org_id, incident_id=incident.id, author_id=author.id, note_type=note_type, body=body, created_at=at))


def seed_demo(db: Session) -> dict[str, Any]:
    if demo_org(db) is not None:
        raise RuntimeError("Demo workspace already exists. Reset it first.")
    rng = random.Random(20260115)  # deterministic
    now = datetime.now(UTC).replace(minute=0, second=0, microsecond=0)

    org = Organization(name=DEMO_ORG_NAME, slug=DEMO_SLUG, is_demo=True)
    db.add(org)
    db.flush()
    users: dict[str, User] = {}
    for email, name, role in DEMO_USERS:
        u = User(org_id=org.id, email=email, display_name=name, role=role, is_demo=True, password_hash=None)
        db.add(u)
        users[name] = u
    db.flush()
    analyst, analyst2, lead = users["Demo Analyst"], users["Demo Analyst Two"], users["Demo Lead"]
    sync_rule_metadata(db)
    sync_playbooks(db)

    ctx = RequestContext(org_id=org.id, user_id=None, actor_label="system:demo-seed")

    # Fourteen days of history: background noise every day plus scenarios on a fixed schedule.
    schedule = [
        (13, "phish-invoice", "-a"),
        (12, "auth-bruteforce", ""),
        (11, "net-outbound", "-a"),
        (10, "iam-priv-account", "-a"),
        (9, "auth-bruteforce", ""),
        (8, "phish-invoice", "-b"),
        (7, "proc-office-powershell", ""),
        (6, "net-outbound", "-b"),
        (5, "auth-bruteforce", ""),
        (4, "defense-logging-tamper", "-a"),
        (3, "phish-invoice", "-c"),
        (2, "iam-priv-account", "-b"),
        (1, "proc-office-powershell", ""),
        (1, "auth-bruteforce", ""),
        (0, "defense-logging-tamper", ""),
        (0, "net-outbound", ""),
    ]
    for day in range(14, -1, -1):
        run_scenario(db, ctx, org.id, "background", now - timedelta(days=day, hours=8))
    for day, sid, variant in schedule:
        at = now - timedelta(days=day, hours=rng.randint(2, 6), minutes=rng.randint(0, 50))
        run_scenario(db, ctx, org.id, sid, at, variant=variant)
    db.flush()

    alerts = list(db.execute(select(Alert).where(Alert.org_id == org.id).order_by(Alert.first_seen)).scalars())
    by_rule: dict[str, list[Alert]] = defaultdict(list)
    for a in alerts:
        by_rule[a.rule_id].append(a)

    def make(alert_list: list[Alert], title: str, summary: str, tags: list[str], assignee: User | None) -> Incident:
        inc = inc_svc.create_incident(
            db,
            ctx,
            org.id,
            title=title,
            summary=summary,
            severity=alert_list[0].severity,
            tags=tags,
            source="detection",
            created_by=assignee.id if assignee else None,
            alerts=alert_list,
            is_synthetic=True,
        )
        inc.created_at = alert_list[0].last_seen + timedelta(minutes=rng.randint(4, 15))
        inc.assignee_id = assignee.id if assignee else None
        return inc

    def lifecycle(inc: Incident, statuses: list[str], verdict: str | None = None, reason: str | None = None) -> None:
        t = inc.created_at
        for st in statuses:
            t += timedelta(minutes=rng.randint(6, 95))
            if inc.acknowledged_at is None:
                inc.acknowledged_at = t
            if st == "contained":
                inc.contained_at = t
            if st == "resolved":
                inc.resolved_at = t
            if st == "closed":
                inc.closed_at = t
                inc.resolved_at = inc.resolved_at or t
                inc.verdict, inc.closure_reason = verdict, reason
            inc.status = st
            db.add(IncidentNote(org_id=org.id, incident_id=inc.id, note_type="system", body=f"Status changed to {st}.", created_at=t))
        inc.updated_at = t

    # Phishing: the first invoice phish is a closed true positive; the first newsletter alert is a benign positive.
    mail = by_rule["SF-MAIL-001"]
    phish = [a for a in mail if "invoice-portal" in a.dedup_key]
    newsletter = [a for a in mail if "newsletter" in a.dedup_key]
    if phish:
        inc = make(
            [phish[0]],
            "Invoice phishing link clicked by HR user",
            "Synthetic scenario: invoice-themed phish with failing SPF was clicked from hr-ws-002.",
            ["phishing", "email"],
            analyst,
        )
        lifecycle(
            inc,
            ["investigating", "contained", "resolved", "closed"],
            "true_positive",
            "Message purged from all mailboxes, domain blocked at proxy, user confirmed no credentials were entered.",
        )
        _note(db, inc, analyst, "Proxy logs show a single GET to the landing page and no POST, so credentials were probably not submitted.", inc.created_at + timedelta(minutes=20))
        _note(db, inc, lead, "Agree with closure. Recommend adding invoice-portal.example to the mail block list.", inc.created_at + timedelta(hours=3), "assessment")
    if newsletter:
        inc = make(
            [newsletter[0]],
            "Newsletter link flagged by phishing correlation",
            "Synthetic scenario: weekly digest from a known sender, SPF and DKIM pass.",
            ["phishing", "false-alarm"],
            analyst2,
        )
        lifecycle(inc, ["investigating", "closed"], "benign_positive", "Expected newsletter from an approved sender; rule behaved as designed but the activity is wanted.")
        _note(db, inc, analyst2, "Sender is on the approved list and authentication passed. Benign positive.", inc.created_at + timedelta(minutes=12))

    # Brute force: active investigation with a firewall block awaiting approval.
    auth = by_rule["SF-AUTH-001"]
    if auth:
        inc = make(
            [auth[-1]],
            "VPN account signed in after password guessing",
            "Synthetic scenario: nine failures from 203.0.113.45 then a successful VPN session for fin.user01.",
            ["credential-access", "vpn"],
            analyst,
        )
        lifecycle(inc, ["investigating"])
        _note(
            db, inc, analyst, "Source address has no prior history in our telemetry. User is on leave per HR, so the success is unexpected.", inc.created_at + timedelta(minutes=18)
        )
        db.add(Indicator(org_id=org.id, ioc_type="ipv4", value="203.0.113.45", analyst_verdict="malicious", analyst_note="Password guessing source (synthetic)."))
        db.flush()
        from app.models import IncidentIndicator, PlaybookRun, ResponseAction

        ind = db.execute(select(Indicator).where(Indicator.org_id == org.id, Indicator.value == "203.0.113.45")).scalar_one()
        db.add(IncidentIndicator(incident_id=inc.id, indicator_id=ind.id))
        run = PlaybookRun(
            org_id=org.id,
            playbook_id="simulate_firewall_block",
            incident_id=inc.id,
            requested_by=analyst.id,
            status="awaiting_approval",
            idempotency_key=f"seed-{inc.id}-block",
            output={"message": "Awaiting approval from a lead who did not request it."},
        )
        db.add(run)
        db.flush()
        db.add(
            ResponseAction(
                org_id=org.id,
                incident_id=inc.id,
                playbook_run_id=run.id,
                action_type="simulate_firewall_block",
                parameters={"ip_addresses": ["203.0.113.45"], "duration_hours": 24},
                requested_by=analyst.id,
                status="pending_approval",
                requires_approval=True,
                simulated=True,
                rollback_plan="Remove the simulated deny entries.",
                idempotency_key=f"seed-{inc.id}-block:action",
            )
        )

    # Privileged account: contained.
    iam = by_rule["SF-IAM-001"]
    if iam:
        inc = make(
            [iam[0]],
            "Unexpected Domain Admin account created by service account",
            "Synthetic scenario: svc_backup created helpdesk_tmp and added it to Domain Admins.",
            ["persistence", "identity"],
            lead,
        )
        lifecycle(inc, ["investigating", "contained"])
        _note(db, inc, lead, "No change ticket found. Account disabled and removed from Domain Admins; svc_backup credentials rotated.", inc.created_at + timedelta(minutes=40))

    # Latest endpoint compromise chain: new, unassigned, combining process, network and logging alerts.
    proc = by_rule["SF-PROC-001"]
    if proc:
        latest_day = max(a.first_seen for a in proc).date()
        chain = [a for a in alerts if a.first_seen.date() >= latest_day - timedelta(days=1) and a.rule_id in ("SF-PROC-001", "SF-DEF-001") and a.incident_id is None]
        if chain:
            make(
                chain,
                "Macro document led to encoded PowerShell on fin-ws-014",
                "Synthetic scenario: Office spawned encoded PowerShell and certutil, followed by logging tampering.",
                ["execution", "endpoint"],
                None,
            )

    db.flush()
    audit.record(db, ctx, "demo.seeded", target_type="organization", target_id=org.id, details={"alerts": len(alerts)})
    return {"org_id": str(org.id), "alerts": len(alerts)}


def reset_demo(db: Session, confirmation: str) -> bool:
    """Delete the demo organisation and everything in it. Requires the exact confirmation phrase."""
    if confirmation != RESET_CONFIRMATION:
        raise ValueError(f"Confirmation phrase must be exactly: {RESET_CONFIRMATION}")
    org = demo_org(db)
    if org is None:
        return False
    if not org.is_demo:
        raise RuntimeError("Refusing to delete a non-demo organisation")
    # Audit logs are append-only; this setting is the only way the trigger allows deletion.
    db.execute(text("SET LOCAL sentinelforge.allow_audit_purge = 'demo-reset'"))
    db.execute(delete(Organization).where(Organization.id == org.id, Organization.is_demo.is_(True)))
    return True
